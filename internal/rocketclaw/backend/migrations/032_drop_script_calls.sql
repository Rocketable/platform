-- Calls made inside execute scripts are no longer kept. The files a turn attached
-- were found through them, so each file now names the turn whose final reply sends it.
ALTER TABLE attachments ADD COLUMN turn_id TEXT NOT NULL DEFAULT '', ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;

UPDATE attachments a SET turn_id = sent.turn_id
FROM (
    SELECT turn.turn_id, file.id
    FROM (
        SELECT entry_json::jsonb->>'turn_id' AS turn_id, entry_json::jsonb->'output_trace' AS trace FROM session_entries
        WHERE strpos(entry_json::text, '"parent_call_id"') > 0
        UNION ALL
        SELECT id, output_trace_json::jsonb FROM active_turns WHERE strpos(output_trace_json, '"parent_call_id"') > 0
    ) turn
    CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(turn.trace) = 'array' THEN turn.trace ELSE '[]' END) item
    CROSS JOIN LATERAL regexp_split_to_table(substr(item->>'output', length('queued attachments for final response: ') + 1), ' ') AS file(id)
    WHERE turn.turn_id <> '' AND item->>'type' = 'function_call_output' AND item->>'parent_call_id' <> ''
        AND starts_with(item->>'output', 'queued attachments for final response: ')
) sent
WHERE a.id = sent.id;

-- +migrate StatementBegin
CREATE FUNCTION pg_temp.drop_script_calls(trace jsonb) RETURNS jsonb LANGUAGE sql AS $$
    SELECT COALESCE(jsonb_agg(item ORDER BY ordinal), '[]')
    FROM jsonb_array_elements(trace) WITH ORDINALITY AS items(item, ordinal)
    WHERE COALESCE(item->>'parent_call_id', '') = '' OR item->>'type' NOT IN ('function_call', 'function_call_output')
$$;
-- +migrate StatementEnd

UPDATE session_entries SET entry_json = jsonb_set(entry_json::jsonb, '{output_trace}', pg_temp.drop_script_calls(entry_json::jsonb->'output_trace'))::json
WHERE strpos(entry_json::text, '"parent_call_id"') > 0 AND jsonb_typeof(entry_json::jsonb->'output_trace') = 'array';

UPDATE active_turns SET output_trace_json = pg_temp.drop_script_calls(output_trace_json::jsonb)::text
WHERE strpos(output_trace_json, '"parent_call_id"') > 0 AND jsonb_typeof(output_trace_json::jsonb) = 'array';

DROP FUNCTION pg_temp.drop_script_calls(jsonb);

-- +migrate Down
ALTER TABLE attachments DROP COLUMN seq, DROP COLUMN turn_id;
