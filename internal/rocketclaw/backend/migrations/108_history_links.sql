CREATE TABLE history_links (
    conversation_id text NOT NULL REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    entry_id bigint NOT NULL,
    parent_entry_id bigint,
    parent_length integer,
    seq bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (entry_id, conversation_id)
);

CREATE INDEX history_links_leaf ON history_links (conversation_id, seq);
CREATE INDEX history_links_children ON history_links (conversation_id, parent_entry_id);

WITH shown AS (
    SELECT conversation_id, id FROM entries
    UNION SELECT r.reports_to, e.id FROM conversations r JOIN entries e USING (conversation_id) WHERE r.reports_to IS NOT NULL
    UNION SELECT c.conversation_id, e.id FROM conversations c JOIN entries e ON e.conversation_id = c.continues
)
INSERT INTO history_links (conversation_id, entry_id, parent_entry_id)
SELECT conversation_id, id, lag(id) OVER (PARTITION BY conversation_id ORDER BY id) FROM shown ORDER BY id;

WITH staged AS (
    SELECT conversation_id, kind, split_part(revert_message_id, ':', 1)::bigint AS entry_id, split_part(revert_message_id, ':', 2)::integer AS idx
    FROM conversations WHERE revert_message_id <> '' AND shadow_parent IS NULL
), later_items AS (
    SELECT s.conversation_id, s.kind, e.conversation_id <> s.conversation_id AS synced, i.item
    FROM staged s JOIN history_links l ON l.conversation_id = s.conversation_id JOIN entries e ON e.id = l.entry_id AND e.id >= s.entry_id
    CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN json_typeof(e.entry_json->'replay_input') = 'array' THEN e.entry_json::jsonb->'replay_input' ELSE '[]' END) WITH ORDINALITY AS i(item, ordinal)
    WHERE e.id > s.entry_id OR i.ordinal - 1 >= s.idx
), cancelled AS (
    SELECT DISTINCT conversation_id FROM later_items
    WHERE synced AND COALESCE(item->>'type', '') NOT IN ('compaction', 'compaction_summary')
        OR item->>'role' = 'user' AND (item->>'prompt_header' !~ '^\[(Web|System)[ \]]' OR item->>'prompt_header' IS NULL AND kind = 'slack_thread')
)
UPDATE conversations c SET revert_message_id = '' FROM cancelled x WHERE c.conversation_id = x.conversation_id OR c.shadow_parent = x.conversation_id;

WITH unlinked AS (
    SELECT c.conversation_id, split_part(c.revert_message_id, ':', 1)::bigint AS entry_id FROM conversations c
    LEFT JOIN history_links l ON l.conversation_id = c.conversation_id AND l.entry_id = split_part(c.revert_message_id, ':', 1)::bigint
    WHERE c.revert_message_id <> '' AND l.entry_id IS NULL
), earlier AS (
    SELECT DISTINCT ON (u.conversation_id) u.conversation_id, e.id::text || ':' || jsonb_array_length(CASE WHEN json_typeof(e.entry_json->'replay_input') = 'array' THEN e.entry_json::jsonb->'replay_input' ELSE '[]' END)::text AS marker
    FROM unlinked u JOIN history_links l ON l.conversation_id = u.conversation_id AND l.entry_id < u.entry_id JOIN entries e ON e.id = l.entry_id
    ORDER BY u.conversation_id, l.entry_id DESC
), first_links AS (
    SELECT DISTINCT ON (u.conversation_id) u.conversation_id, l.entry_id::text || ':0' AS marker FROM unlinked u JOIN history_links l USING (conversation_id)
    ORDER BY u.conversation_id, l.seq
)
UPDATE conversations c SET revert_message_id = COALESCE(e.marker, f.marker, '')
FROM unlinked u LEFT JOIN earlier e USING (conversation_id) LEFT JOIN first_links f USING (conversation_id) WHERE c.conversation_id = u.conversation_id;

ANALYZE history_links;

