//go:build linux

// Command rootfs moves the emulated shell's guest image to the newest Ubuntu archive snapshot. `go generate
// ./internal/rocketclaw/sandbox` runs it, through make, so on a Mac it runs on Linux. It builds the image for
// amd64 and arm64 with mmdebstrap (qemu-user emulation runs the other architecture) in a temporary folder.
// When a package version changed, it writes the snapshot to snapshot.gen.go, the versions to
// packages.<arch>.lock, and an SBOM per architecture beside this file; otherwise it changes nothing, so hosts
// do not rebuild an identical image. Commit what it writes: each host builds the new image at its next start.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	"github.com/Rocketable/platform/internal/rocketclaw/sandbox"
)

func main() {
	pc := make([]uintptr, 1)
	runtime.Callers(1, pc)
	self, _ := runtime.CallersFrames(pc).Next()

	changed, err := update(filepath.Dir(self.File), time.Now().UTC().Format("20060102T150405Z"))
	if err != nil {
		log.Fatal("rootfs: ", err)
	}

	if !changed {
		log.Print("rootfs: the newest snapshot changes no package; nothing to update")
	}
}

// update builds both architectures' images from snapshot and, when any package version differs from the
// locks, writes snapshot, locks and SBOMs. It reports whether it wrote them.
func update(dir, snapshot string) (bool, error) {
	type build struct {
		arch, release string
		installed     []string
	}

	var (
		builds  []build
		changed bool
	)

	for _, arch := range []string{"amd64", "arm64"} {
		installed, release, err := buildImage(snapshot, arch)
		if err != nil {
			return false, err
		}

		old, _ := os.ReadFile(filepath.Join(dir, "..", "packages."+arch+".lock"))
		changed = changed || !bytes.Equal(old, []byte(strings.Join(installed, "\n")+"\n"))
		builds = append(builds, build{arch, release, installed})
	}

	if !changed {
		return false, nil
	}

	for _, b := range builds {
		lock := filepath.Join(dir, "..", "packages."+b.arch+".lock")
		if err := os.WriteFile(lock, []byte(strings.Join(b.installed, "\n")+"\n"), 0o644); err != nil {
			return false, fmt.Errorf("write lock: %w", err)
		}

		if err := writeSBOM(filepath.Join(dir, "sandbox-rootfs-"+b.arch+".spdx.json"), snapshot, b.arch, b.release, b.installed); err != nil {
			return false, err
		}
	}

	pin := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\n\npackage sandbox\n\n// Snapshot is the Ubuntu archive moment every package of the guest image comes from.\nconst Snapshot = %q\n", snapshot)
	if err := os.WriteFile(filepath.Join(dir, "..", "snapshot.gen.go"), []byte(pin), 0o644); err != nil {
		return false, fmt.Errorf("write snapshot: %w", err)
	}

	return true, nil
}

// buildImage builds arch's image from snapshot in a temporary folder, the same every run, and removes it. It is
// not the repository's .tmp: on a Mac, whose folders this runs in through the Linux container, that is
// case-insensitive, and Ubuntu has pam.7.gz and PAM.7.gz.
func buildImage(snapshot, arch string) (installed []string, release string, err error) {
	tmp := filepath.Join(os.TempDir(), "rocketclaw-sandbox-image")
	defer func() { _ = os.RemoveAll(tmp) }()

	installed, release, err = sandbox.BuildImage(context.Background(), snapshot, arch, filepath.Join(tmp, "rootfs"), "")
	if err != nil {
		// The error names mmdebstrap's first error line; whoever runs this needs its whole output.
		if b, ok := errors.AsType[*sandbox.BuildError](err); ok {
			_, _ = os.Stderr.Write(b.Output)
		}

		return nil, "", fmt.Errorf("build %s image: %w", arch, err)
	}

	return installed, release, nil
}

// writeSBOM writes an SPDX 2.3 document listing every installed package.
func writeSBOM(path, snapshot, arch, release string, pkgs []string) error {
	type ref struct {
		Category string `json:"referenceCategory"`
		Type     string `json:"referenceType"`
		Locator  string `json:"referenceLocator"`
	}

	type pkg struct {
		SPDXID           string `json:"SPDXID"`
		Name             string `json:"name"`
		Version          string `json:"versionInfo"`
		DownloadLocation string `json:"downloadLocation"`
		Supplier         string `json:"supplier"`
		ExternalRefs     []ref  `json:"externalRefs"`
	}

	type creationInfo struct {
		Created  string   `json:"created"`
		Creators []string `json:"creators"`
	}

	created, _ := time.Parse("20060102T150405Z", snapshot)

	doc := struct {
		SPDXVersion  string       `json:"spdxVersion"`
		DataLicense  string       `json:"dataLicense"`
		SPDXID       string       `json:"SPDXID"`
		Name         string       `json:"name"`
		Namespace    string       `json:"documentNamespace"`
		CreationInfo creationInfo `json:"creationInfo"`
		Packages     []pkg        `json:"packages"`
	}{
		SPDXVersion: "SPDX-2.3", DataLicense: "CC0-1.0", SPDXID: "SPDXRef-DOCUMENT",
		Name:         "rocketclaw-sandbox-rootfs-" + arch,
		Namespace:    fmt.Sprintf("https://github.com/Rocketable/platform/sandbox-rootfs/%s/%s", snapshot, arch),
		CreationInfo: creationInfo{created.Format(time.RFC3339), []string{"Tool: internal/rocketclaw/sandbox/rootfs"}},
	}

	for _, p := range pkgs {
		name, version, _ := strings.Cut(p, "=")
		doc.Packages = append(doc.Packages, pkg{
			SPDXID:           "SPDXRef-Package-" + strings.ReplaceAll(name, "+", "-"), // dpkg names are [a-z0-9.+-]
			Name:             name,
			Version:          version,
			DownloadLocation: "NOASSERTION",
			Supplier:         "Organization: Canonical",
			ExternalRefs:     []ref{{"PACKAGE-MANAGER", "purl", fmt.Sprintf("pkg:deb/ubuntu/%s@%s?arch=%s&distro=ubuntu-%s", name, version, arch, release)}},
		})
	}

	data, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return fmt.Errorf("sbom: %w", err)
	}

	if err := os.WriteFile(path, append(data, '\n'), 0o644); err != nil {
		return fmt.Errorf("sbom: %w", err)
	}

	return nil
}
