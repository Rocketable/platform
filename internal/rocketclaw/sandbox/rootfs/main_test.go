// TestMain lets this binary stand in for mmdebstrap: it writes the smallest Ubuntu-like tar the build
// accepts where the real one would, the path after the suite argument.
func TestMain(m *testing.M) {
	if filepath.Base(os.Args[0]) != "mmdebstrap" {
		os.Exit(m.Run())
	}

	if os.Getenv("MMDEBSTRAP_FAIL") == "1" {
		os.Exit(1)
	}

	f, err := os.Create(os.Args[slices.Index(os.Args, "resolute")+1])
	if err != nil {
		panic(err)
	}

	tw := tar.NewWriter(f)

	for _, e := range []struct{ name, data string }{
		{"./etc/", ""}, {"./usr/", ""}, {"./usr/lib/", ""}, {"./usr/local/", ""}, {"./usr/local/bin/", ""},
		{"./var/", ""}, {"./var/lib/", ""}, {"./var/lib/dpkg/", ""},
		{"./etc/passwd", "root:x:0:0:root:/root:/bin/bash\n"},
		{"./etc/group", "root:x:0:\n"},
		{"./usr/lib/os-release", "VERSION_ID=\"26.04\"\n"},
		{"./var/lib/dpkg/status", "Package: libc++1\nStatus: install ok installed\nVersion: 1:21\n\nPackage: bash\nStatus: install ok installed\nVersion: 5.3-2ubuntu1\n"},
	} {
		h := &tar.Header{Typeflag: tar.TypeReg, Name: e.name, Mode: 0o644, Size: int64(len(e.data))}
		if e.name[len(e.name)-1] == '/' {
			h.Typeflag, h.Mode = tar.TypeDir, 0o755
		}

		if err := tw.WriteHeader(h); err != nil {
			panic(err)
		}

		if _, err := io.WriteString(tw, e.data); err != nil {
			panic(err)
		}
	}

	if err := tw.Close(); err != nil {
		panic(err)
	}

	if err := f.Close(); err != nil {
		panic(err)
	}

	os.Exit(0)
}

// update builds both architectures from the given snapshot and, when a package changed, writes the snapshot,
// the locks beside the sandbox package and the SBOMs beside the tool, leaving no image in the repository's
// .tmp. A snapshot that changes no package changes nothing, so hosts do not rebuild an identical image.
func TestUpdate(t *testing.T) {
	self, err := os.Executable()
	require.NoError(t, err)

	bin := t.TempDir()
	require.NoError(t, os.Symlink(self, filepath.Join(bin, "mmdebstrap")))
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))

	repo := t.TempDir()
	dir := filepath.Join(repo, "internal", "rocketclaw", "sandbox", "rootfs")
	require.NoError(t, os.MkdirAll(dir, 0o755))

	tmp := t.TempDir()
	t.Setenv("TMPDIR", tmp)

	changed, err := update(dir, "20261102T030405Z")
	require.NoError(t, err)
	require.True(t, changed)

	for _, arch := range []string{"amd64", "arm64"} {
		lock, err := os.ReadFile(filepath.Join(dir, "..", "packages."+arch+".lock"))
		require.NoError(t, err)
		require.Equal(t, "bash=5.3-2ubuntu1\nlibc++1=1:21\n", string(lock))
	}

	left, err := os.ReadDir(tmp)
	require.NoError(t, err)
	require.Empty(t, left, "the images are built in a temporary folder and removed")

	pin, err := os.ReadFile(filepath.Join(dir, "..", "snapshot.gen.go"))
	require.NoError(t, err)
	require.Contains(t, string(pin), "// Code generated by go generate; DO NOT EDIT.\n\npackage sandbox\n")
	require.Contains(t, string(pin), "const Snapshot = \"20261102T030405Z\"\n")

	data, err := os.ReadFile(filepath.Join(dir, "sandbox-rootfs-arm64.spdx.json"))
	require.NoError(t, err)

	var sbom struct {
		Name         string `json:"name"`
		CreationInfo struct {
			Created string `json:"created"`
		} `json:"creationInfo"`
		Packages []struct {
			SPDXID       string `json:"SPDXID"`
			Name         string `json:"name"`
			Version      string `json:"versionInfo"`
			ExternalRefs []struct {
				Locator string `json:"referenceLocator"`
			} `json:"externalRefs"`
		} `json:"packages"`
	}

	require.NoError(t, json.Unmarshal(data, &sbom))
	require.Equal(t, "rocketclaw-sandbox-rootfs-arm64", sbom.Name)
	require.Equal(t, "2026-11-02T03:04:05Z", sbom.CreationInfo.Created, "the snapshot's moment, so rebuilding writes the same file")
	require.Len(t, sbom.Packages, 2)

	p := sbom.Packages[1]
	require.Equal(t, "SPDXRef-Package-libc--1", p.SPDXID, "SPDX IDs take no +")
	require.Equal(t, "libc++1", p.Name)
	require.Equal(t, "1:21", p.Version)
	require.Equal(t, "pkg:deb/ubuntu/libc++1@1:21?arch=arm64&distro=ubuntu-26.04", p.ExternalRefs[0].Locator)

	changed, err = update(dir, "20261109T000000Z")
	require.NoError(t, err)
	require.False(t, changed, "no package changed")

	unchanged, err := os.ReadFile(filepath.Join(dir, "..", "snapshot.gen.go"))
	require.NoError(t, err)
	require.Equal(t, string(pin), string(unchanged))

	_, err = update(filepath.Join(repo, "missing", "a", "b", "rootfs"), "20261109T000000Z")
	require.ErrorContains(t, err, "write lock:")

	other := filepath.Join(t.TempDir(), "internal", "rocketclaw", "sandbox")
	require.NoError(t, os.MkdirAll(other, 0o755))
	_, err = update(filepath.Join(other, "rootfs"), "20261109T000000Z")
	require.ErrorContains(t, err, "sbom:")

	t.Setenv("MMDEBSTRAP_FAIL", "1")

	_, err = update(dir, "20261109T000000Z")
	require.ErrorContains(t, err, "build amd64 image: mmdebstrap failed (exit status 1)")
}
